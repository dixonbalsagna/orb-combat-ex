// Schema work for Animation's super-heavy tier and the mediums on 12 ticks (docs/animation/super-heavy.md; Animation's own drafts are
// docs/animation/handoff/super-heavy-schema.patch and anim-medium-wind.schema.json). NOT run by CI, the validator or the sim. Run once from the
// repo root, in the commit that lands Animation's data (waves rival7 and protag10 with the new key set fields, and data/anim/medium_wind.json):
//     node docs/tools/pending/apply-anim-superheavy.cjs
// It does NOT edit data/. It adds:
//   tools/schemas/anim-wave-keysets.schema.json  three optional keys on a key set: `tell_at` (number, 0.05 to 1: how far into the wind-up the
//        chamber is reached; held in plain sight from there), `squash_w` (number, 0 to 1: the share of the press style's squash the piece takes) and
//        `drive` (one of Combat's six heavy drives, by id: step_through, turn, unwind, heave, fall, full_turn; strike.heavy.drive in
//        docs/combat/pending/movegen/parts.json, where `word` is stepping, turning, unwinding, heaving, falling and spinning)
//   tools/schemas/anim-medium-wind.schema.json  (anim.mediumwind/1) for the new file data/anim/medium_wind.json, and its map.json entry
//   rules in tools/lib/xref-fight.js:
//     medium-wind-set  every key of `sets` and every `held_only` entry is a key set of a wave (data/anim/waves/*.keysets.json) or of
//                      data/anim/keysets.json; every value of `sets` is a key of `rules`; a key set is in `sets` or in `held_only`, not both
//     keyset-drive     a key set's `drive` is the drive Combat's grammar gives its `path` (strike.heavy.drive.<path>.id), when
//                      data/combat/parts.json is there (it is inert until the movegen script has run)
// Every case sets its own values. Re-runnable (a second run changes nothing).
const fs = require('fs');
const rj = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const wj = (f, o) => fs.writeFileSync(f, JSON.stringify(o, null, 2) + '\n');
const closed = { additionalProperties: false, patternProperties: { '^_': true } };
const clone = (o) => JSON.parse(JSON.stringify(o));
const DRIVES = ['step_through', 'turn', 'unwind', 'heave', 'fall', 'full_turn'];
const SETID = '^[a-z][a-z0-9_]*([.][a-z0-9_~]+)*$';

// =============================== keysets schema ===============================
{
  const f = 'tools/schemas/anim-wave-keysets.schema.json';
  const s = rj(f);
  const row = s.properties.keysets.additionalProperties;
  if (!row.properties.tell_at) {
    const props = {};
    for (const [k, v] of Object.entries(row.properties)) {
      props[k] = v;
      if (k === 'step_max') {
        props.tell_at = { type: 'number', minimum: 0.05, maximum: 1, description: 'A super-heavy piece\'s tell: how far into the wind-up (0 to 1) the chamber is reached; it is then held in plain sight to the blow. 1 (the default) is the old linear ramp.' };
        props.squash_w = { type: 'number', minimum: 0, maximum: 1, description: 'How much of the press style\'s squash this piece takes (0 to 1, default 1): 0 draws its tell in its chamber alone.' };
        props.drive = { enum: DRIVES, description: 'A super-heavy piece\'s drive: what the whole body does behind the limb (Combat\'s strike.heavy.drive, by id: step_through, turn, unwind, heave, fall, full_turn).' };
      }
    }
    if (!props.tell_at) throw new Error('keysets schema has no step_max property to put the new keys beside');
    row.properties = props;
    wj(f, s);
  }
}

// =============================== medium wind schema and map ===============================
{
  const f = 'tools/schemas/anim-medium-wind.schema.json';
  if (!fs.existsSync(f)) {
    const num01 = (d) => ({ type: 'number', minimum: 0, maximum: 1, description: d });
    wj(f, {
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      $id: 'meridian/anim-medium-wind',
      title: 'anim.mediumwind/1',
      description: 'data/anim/medium_wind.json: Combat\'s eight rules for a medium thrown on Y\'s 12-tick wind-up (docs/combat/pending/movegen/parts.json strike.windup), as the body does them (docs/animation/super-heavy.md section 3). Render only, outside the sim\'s data hash; used only with RenderAnim.press_styles and RenderAnim.medium_wind, on the medium press style with a wind-up of 14 ticks or fewer. rules: per rule id (w1 to w8), u_cap (the chamber is reached this far at most, 0 to 1) and step (the share of the key set\'s step the body takes, 0 to 1). sets: key set id to its rule (generated by render/anim/tools/medium_wind_gen.mjs from the moveset rows). held_only: key sets whose rule is w1 to w3, which only play on a held Y and carry no change here. Version field: schema. Policy: closed except keys starting with an underscore. Cross-references (every key of sets and every held_only entry is a key set of a wave; every value of sets is a key of rules; a key set is not in both) are checked by tools/lib/xref-fight.js (medium-wind-set).',
      type: 'object',
      required: ['schema', 'rules', 'sets', 'held_only'],
      properties: {
        schema: { const: 'anim.mediumwind/1' },
        rules: {
          type: 'object',
          description: 'Rule id to its change.',
          propertyNames: { pattern: '^(_.*|w[1-8])$' },
          additionalProperties: Object.assign({
            type: 'object',
            properties: {
              u_cap: num01('The chamber is reached this far at most (a flatter wind-up).'),
              step: num01('The share of the key set\'s step the body takes (a half step is 0.5).'),
              why: { type: 'string', description: 'Combat\'s words for the rule.' },
            },
          }, closed),
          patternProperties: { '^_': true },
        },
        sets: {
          type: 'object',
          description: 'Key set id to the rule that it follows.',
          propertyNames: { pattern: '^(_.*|' + SETID.slice(1, -1) + ')$' },
          additionalProperties: { type: 'string', pattern: '^w[1-8]$' },
          patternProperties: { '^_': true },
        },
        held_only: { type: 'array', items: { type: 'string', pattern: SETID }, uniqueItems: true, description: 'Key set ids of the held-only mediums (rule w1 to w3).' },
      },
      additionalProperties: false,
      patternProperties: { '^_': true },
    });
  }
}
{
  const f = 'tools/schemas/map.json';
  const m = rj(f);
  if (!m.rules.some((r) => r.match === 'data/anim/medium_wind.json')) {
    const i = m.rules.findIndex((r) => r.match === 'data/anim/press_styles.json');
    m.rules.splice(i >= 0 ? i + 1 : m.rules.length, 0, { match: 'data/anim/medium_wind.json', schema: 'anim-medium-wind.schema.json' });
    wj(f, m);
  }
}

// =============================== xref ===============================
{
  const f = 'tools/lib/xref-fight.js';
  let t = fs.readFileSync(f, 'utf8');
  if (!t.includes("'medium-wind-set'")) {
    const marker = '  // ---- anim press styles: the squash poses exist, the fighters and bones are real, a carry has a length ----';
    if (!t.includes(marker)) throw new Error('super-heavy xref marker');
    t = t.replace(marker, () => [
      "  // ---- anim super-heavy: the mediums on 12 ticks name key sets that exist; a key set's drive is its path's ----",
      "  {",
      "    const setIds = new Set();",
      "    const keysetFiles = docsFor(/^data\\/anim\\/waves\\/[^/]+\\.keysets\\.json$/);",
      "    for (const rel of keysetFiles) { const d = get(rel); if (isObj(d) && isObj(d.keysets)) for (const k of Object.keys(d.keysets)) setIds.add(k); }",
      "    const mainKs = get('data/anim/keysets.json');",
      "    if (isObj(mainKs) && isObj(mainKs.keysets)) for (const k of Object.keys(mainKs.keysets)) setIds.add(k);",
      "    const MW = 'data/anim/medium_wind.json';",
      "    const mw = get(MW);",
      "    if (isObj(mw) && setIds.size) {",
      "      const ruleKeys = isObj(mw.rules) ? Object.keys(mw.rules).filter((k) => !k.startsWith('_')) : [];",
      "      const held = new Set(Array.isArray(mw.held_only) ? mw.held_only : []);",
      "      if (isObj(mw.sets)) for (const [id, rule] of Object.entries(mw.sets)) {",
      "        if (id.startsWith('_')) continue;",
      "        if (!setIds.has(id)) err(MW, `/sets/${esc(id)}`, 'medium-wind-set', `\"${id}\" is a key set of no wave`);",
      "        if (typeof rule === 'string' && ruleKeys.length && !ruleKeys.includes(rule)) err(MW, `/sets/${esc(id)}`, 'medium-wind-set', `\"${id}\" follows rule \"${rule}\", which is not a key of rules (${ruleKeys.join(', ')})`);",
      "        if (held.has(id)) err(MW, `/sets/${esc(id)}`, 'medium-wind-set', `\"${id}\" is in sets and in held_only: a key set is one or the other`);",
      "      }",
      "      if (Array.isArray(mw.held_only)) mw.held_only.forEach((id, i) => { if (typeof id === 'string' && !setIds.has(id)) err(MW, `/held_only/${i}`, 'medium-wind-set', `\"${id}\" is a key set of no wave`); });",
      "    }",
      "    const parts = get('data/combat/parts.json');",
      "    const drives = isObj(parts) && isObj(parts.strike) && isObj(parts.strike.heavy) && isObj(parts.strike.heavy.drive) ? parts.strike.heavy.drive : null;",
      "    if (drives) for (const rel of keysetFiles) {",
      "      const d = get(rel);",
      "      if (!isObj(d) || !isObj(d.keysets)) continue;",
      "      for (const [id, ks] of Object.entries(d.keysets)) {",
      "        if (!isObj(ks) || typeof ks.drive !== 'string' || typeof ks.path !== 'string' || !isObj(drives[ks.path])) continue;",
      "        if (drives[ks.path].id !== ks.drive) err(rel, `/keysets/${esc(id)}/drive`, 'keyset-drive', `key set \"${id}\" has drive \"${ks.drive}\", but Combat's grammar gives a heavy on path \"${ks.path}\" the drive \"${drives[ks.path].id}\"`);",
      "      }",
      "    }",
      "  }",
      marker,
    ].join('\n'));
    fs.writeFileSync(f, t);
  }
}

