// The pools of data/combat/recipes.json, written from the generated cells (cells.json `pools`), and the coverage of what each
// fighter has today: every pool of the live recipes is compared with what the generator gives, and every piece the generator
// does not give is named with the reason it cannot (his never rows, Legal's rows, the grammar, no key set) or does not (the
// cell is full).
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { bannedHit, env, flagsOf, formsOf, load, manifestOf, match, posed, shapeRows } from './generator.mjs';
import { dumps, get, has, sorted, truthy } from './py.mjs';

const pieceId = (m) => get(get(m, 'keys', {}), 'strike') || get(get(m, 'keys', {}), 'from');

/** A fighter to a pool to a list of {id, status}, the recipes file's own shape. Kit rows (the guards) have no pools. */
export function buildPools(out, parts, cells, identity) {
  const spec = get(cells, 'pools');
  if (!truthy(spec)) return {};
  const res = {};
  for (const who of sorted(Object.keys(out))) {
    const idn = identity.fighters[who];
    if (truthy(get(idn, 'kit'))) continue;
    const doc = out[who];
    const pools = {};
    for (const [name, r] of Object.entries(spec.rules)) {
      const cell = get(doc.cells, r.from);
      if (!cell) continue;
      const quota = r.quota ? get(cells.stances, r.from.split('.')[0], {})[r.from.split('.')[1]].quotas.find((q) => q.name === r.quota) : null;
      const also = r.also ? new Set(get(idn, r.also, []) || []) : new Set();
      const keep = (m) => {
        if (also.has(m.id)) return true;
        if (r.form && !get(m, 'forms', []).includes(r.form)) return false;
        if (r.filter && !match(r.filter, m)) return false;
        if (quota && !match(has(quota, 'any') ? { any: quota.any } : quota.filter, m)) return false;
        if (r.burst && !match(parts.strike.burst.classes[r.burst].when, m)) return false;
        if (r.neverAs && idn.never.some((n) => match(n.shape, { ...m, weight: r.neverAs }))) return false;
        return true;
      };
      const rows = [];
      for (const m of cell.moves) {
        const level = get(get(m, 'keys', {}), 'level');
        const plays = m.status === 'posed' || spec.levels.includes(level);
        const id = pieceId(m);
        if (!plays || !id || !keep(m) || rows.some((x) => x.id === id)) continue;
        rows.push({ id, status: 'posed', _from: m.id, _wave: get(m.keys, 'wave') });
      }
      if (rows.length) pools[name] = rows;
    }
    res[who] = pools;
  }
  return res;
}

/** pools.json: the pools in the recipes shape, without the working notes. */
export function poolsText(pools, cells) {
  const clean = {};
  for (const [who, ps] of Object.entries(pools)) clean[who] = Object.fromEntries(Object.entries(ps).map(([n, rows]) => [n, rows.map((r) => ({ id: r.id, status: r.status }))]));
  return dumps({
    schema: 'combat.movegen.pools/1',
    _about: 'GENERATED by tools/movegen/movegen.mjs from the moveset files and cells.json `pools`. The pools of data/combat/recipes.json as the generator writes them: '
      + 'a fighter to a pool to a list of {id, status}, the shape of the recipes file\'s `pools` (tools/schemas/combat-recipes.schema.json). PARKED: nothing reads it; '
      + 'coverage.md compares it with the live recipes.',
    rules: Object.keys(cells.pools.rules),
    pools: clean,
  }, { indent: 1, ensureAscii: false }) + '\n';
}

/** Why a piece of his live recipes is not among his generated moves: a reason in plain words. */
function whyNot(ctx, who, sid) {
  const { parts, identity, out, cells } = ctx;
  const idn = identity.fighters[who];
  const g = parts.strike;
  const row = idn.waves.map((w) => [w, manifestOf(w).strikes.find((s) => s.combat === sid)]).find(([, s]) => s);
  if (!row) return { kind: 'no key set', why: `no pack of his (${idn.waves.join(', ')}) poses it` };
  const [wave, s] = row;
  if (ctx.notes[who].unread.some((u) => u.startsWith(s.id + ' '))) return { kind: 'grammar', why: `the grammar cannot read its key set ${s.id} (${s.limb}, ${get(s, 'tip')}, ${get(s, 'path')}, ${s.target}): ${s.limb.startsWith('tail') ? 'a tail is a limb the grammar does not have yet (the `own` limb, design section 7)' : 'its tip, path or place is outside the tables'}` };
  const [cover] = posed(parts, idn, ctx.tips);
  const entry = [...cover.values()].find((e) => e.from === sid && e.level === 'posed') || [...cover.values()].find((e) => e.from === sid);
  if (!entry) {
    const limb = s.limb.replace(/_[rl]$/, '');
    const key = [limb, get(get(idn, 'tipOf', {}), sid, get(s, 'tip')), get(s, 'path'), s.target.startsWith('arm') ? 'arm' : s.target, get(get(g, 'animWeight', {}), s.weight, s.weight)];
    const other = cover.get(key.join('\u0001'));
    if (other) {
      return { kind: 'another key set', why: `its shape (${key[0]} ${key[1]}, ${String(key[2]).replace('_', ' ')} to the ${key[3]}, ${key[4]}${get(get(s, 'uses', {}), 'arms', 1) === 2 ? ', both arms' : ''}) is read on \`${other.set}\` (${other.from}): the generator keeps one key set a shape, preferring the nearest level and one arm` };
    }
    return { kind: 'grammar', why: `its key set ${s.id} in ${wave} gives no shape he may have` };
  }
  const [limb, tip, path, target, weight] = entry._key;
  const m = { limb, tip, path, target, weight };
  const shape = `${limb} ${tip}, ${path.replace('_', ' ')} to the ${target} (${weight})`;
  const never = idn.never.find((n) => match(n.shape, m));
  if (never) return { kind: 'his never row', why: `${shape}: his never row "${get(never, 'why', JSON.stringify(never.shape))}"` };
  const flags = flagsOf(g, idn, m, entry);
  const forms = formsOf(g, m, entry.arms, flags.has);
  const refused = shapeRows(parts).filter((r) => bannedHit(r, m, forms, entry.arms, flags) === 'match').map((r) => r.id);
  if (refused.length) return { kind: "Legal's rows", why: `${shape}: refused by Legal's ${refused.join(', ')}` };
  const holder = Object.entries(out[who].cells).find(([, c]) => c.kind === 'strikes' && c.moves.some((x) => x.limb === limb && x.tip === tip && x.path === path && x.target === target && x.weight === weight));
  if (holder) return { kind: 'another key set', why: `${shape}: his ${holder[0]} has this shape on another key set (${holder[1].moves.find((x) => x.limb === limb && x.tip === tip && x.path === path && x.target === target && x.weight === weight).keys.from || 'new'})` };
  const cellOf = { light: 'martial.x', medium: 'martial.y', heavy: 'martial.b' }[weight];
  const cell = get(get(cells.stances, 'martial', {}), cellOf.split('.')[1], {});
  const n = cell.count + Math.trunc(Number(get(get(idn, 'adds', {}), cellOf, 0)));
  return { kind: 'not picked', why: `${shape}: a shape he may have, not picked: ${cellOf} holds ${n} and its quotas and spread chose others` };
}

/** coverage.md, and the findings it rests on: { text, problems } (a problem: a piece a brawl pool has today that the generated pools do not give). */
export function coverage(ctx) {
  const { out, pools, recipesPath } = ctx;
  const rec = existsSync(recipesPath) ? load(recipesPath) : { pools: {} };
  const rel = recipesPath.slice(env.root.length + 1).split('\\').join('/');
  const L = [];
  const P = (s = '') => L.push(s);
  const problems = [];
  P('# Coverage: the generated movesets against what the fighters have today');
  P();
  P(`GENERATED by \`tools/movegen/movegen.mjs\`. Do not edit. Compared with \`${rel}\`, pool by pool. A generated pool is written from the cells by the rules in \`cells.json\` \`pools\` (\`pools.json\`). The brawl's pools are the ones the generator owns; the older pools (the blur patterns, the combo and the power pools) are hand-kept from before it, and for them this lists every piece the generator does not give, with the reason.`);
  P();
  for (const who of sorted(Object.keys(pools))) {
    const live = get(get(rec, 'pools', {}), who);
    if (!live) continue;
    const gen = pools[who];
    const livePacks = new Set();
    for (const rows of Object.values(gen)) for (const r of rows) if (Object.values(live).some((lr) => lr.some((x) => x.id === r.id))) livePacks.add(r._wave);
    P(`## ${who === 'rival' ? 'The rival' : 'The ' + who.charAt(0).toUpperCase() + who.slice(1)}`);
    P();
    P('| Pool | Today | Generated | Today\'s pieces the generator gives | Order | Added by the generator |');
    P('| :--- | ---: | ---: | :--- | :--- | :--- |');
    const older = [];
    for (const [name, lrows] of Object.entries(live)) {
      if (name.startsWith('_')) continue;
      const g = get(gen, name);
      if (!g) {
        older.push(name);
        continue;
      }
      const lids = lrows.map((r) => r.id);
      const gids = g.map((r) => r.id);
      const missing = lids.filter((i) => !gids.includes(i));
      const extra = g.filter((r) => !lids.includes(r.id));
      const newer = extra.filter((r) => !livePacks.has(r._wave));
      const other = extra.filter((r) => livePacks.has(r._wave));
      const sameOrder = JSON.stringify(gids.filter((i) => lids.includes(i))) === JSON.stringify(lids.filter((i) => gids.includes(i)));
      for (const i of missing) problems.push(`${who}: ${name} has ${i} today, and the generated pool does not`);
      for (const r of other) problems.push(`${who}: the generated ${name} adds ${r.id} (${r._from}) from a pack the live pools already draw on`);
      const added = [...(newer.length ? [`${newer.map((r) => '`' + r.id + '`').join(', ')} (${sorted([...new Set(newer.map((r) => r._wave))]).join(', ')}: packs the live recipes predate)`] : []),
        ...(other.length ? [`**${other.map((r) => '`' + r.id + '`').join(', ')}**`] : [])];
      P(`| ${name} | ${lids.length} | ${gids.length} | ${missing.length ? `**all but ${missing.join(', ')}**` : 'all'} | ${sameOrder ? 'the same' : 'differs'} | ${added.join('; ') || '-'} |`);
    }
    P();
    if (older.length) {
      P(`**The older pools** (${older.join(', ')}): hand-kept before the generator, and not written by it. Every piece they name and the generator gives is in one of his cells; the others, with why:`);
      P();
      const all = new Set(Object.values(out[who].cells).flatMap((c) => get(c, 'moves', []).map(pieceId)).filter(Boolean));
      const named = [];
      for (const name of older) for (const r of live[name]) if (!named.includes(r.id)) named.push(r.id);
      const gone = named.filter((i) => !all.has(i));
      P(`${named.length - gone.length} of the ${named.length} pieces they name are generated.`);
      P();
      if (gone.length) {
        P('| Piece | In | Today | Why the generator does not give it |');
        P('| :--- | :--- | :--- | :--- |');
        for (const i of gone) {
          const inPools = older.filter((n) => live[n].some((r) => r.id === i));
          const status = [...new Set(older.flatMap((n) => live[n].filter((r) => r.id === i).map((r) => r.status)))].join(', ');
          const w = whyNot(ctx, who, i);
          P(`| \`${i}\` | ${inPools.join(', ')} | ${status} | **${w.kind}:** ${w.why} |`);
        }
        P();
      }
    }
  }
  P('## What the generator cannot express');
  P();
  P('- **A limb it does not have.** The rival\'s tail strikes (`strike.tail_*`, waiting in today\'s older pools) need the `own` limb in `parts.json` (design section 7). Until it exists they stay hand-kept.');
  P('- **A shape his identity or Legal refuses.** Today\'s older pools still name pieces his `never` rows or Legal\'s rows now refuse (above). The generator never offers them; the hand-kept pools are older than the rows.');
  P('- **A pool that is not a cell.** The blur patterns, the combo links and accents, and the power pools are hand-kept tables of strike ids from before the generator; they are not written from cells, and `cells.json` `pools` has no rule for them. The pools the brawl reads are all written.');
  P('- **Set pieces and frames.** Context actions, signature frames and the specials\' frames are lists or frames, not generated (`cells.json`).');
  P();
  return { text: L.join('\n') + '\n', problems };
}

export function poolsCtx(r, recipesPath) {
  const tips = existsSync(join(env.root, 'data', 'anim', 'tips.json')) ? load(join(env.root, 'data', 'anim', 'tips.json')) : {};
  const pools = buildPools(r.out, r.parts, r.cells, r.identity);
  return { ...r, tips, pools, recipesPath };
}
